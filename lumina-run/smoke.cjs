const {chromium}=require("playwright");
const fs=require("node:fs");
const path=require("node:path");
(async()=>{
 const browser=await chromium.launch({headless:true,args:["--no-sandbox","--enable-webgl","--use-angle=swiftshader","--enable-unsafe-swiftshader"]});
 const errors=[];
 const context=await browser.newContext({viewport:{width:1440,height:900},hasTouch:true,deviceScaleFactor:1});
 const desktop=await context.newPage();
 desktop.on("pageerror",e=>errors.push("desktop pageerror "+e.message));
 const target="http://127.0.0.1:8765/lumina-run/?qa=1";
 await desktop.goto(target,{waitUntil:"domcontentloaded",timeout:30000});
 await desktop.locator("#world canvas").waitFor({timeout:60000});
 await desktop.waitForFunction(()=>Boolean(window.__luminaQA),null,{timeout:60000});
 await desktop.waitForTimeout(1800);
 await desktop.screenshot({path:path.join(__dirname,"screenshot-desktop.png"),fullPage:true});
 if(!(await desktop.locator('[data-stage="1"]').isDisabled()))throw Error("Stage 2 must start locked");
 await desktop.locator("#start").click();
 await desktop.waitForFunction(()=>window.__luminaQA?.get().mode==="playing");
 const song0=await desktop.evaluate(()=>window.__luminaQA.get());
 if(song0.bpm!==100||song0.noteCount<20)throw Error("Stage 1 lacks playable rhythm chart");
 const beforeNotes=song0.lumens;
 const qaHit=await desktop.evaluate(()=>window.__luminaQA.testBeatHit());
 if(!qaHit||await desktop.evaluate(()=>window.__luminaQA.get().lumens)!==beforeNotes+1)throw Error("Rhythm judgement failed to award note");
 await desktop.keyboard.press("ArrowRight");
 await desktop.keyboard.press("Space");
 await desktop.evaluate(()=>window.__luminaQA.win());
 if(await desktop.locator("#next-stage").isHidden())throw Error("Missing next-level button after stage 1");
 await desktop.locator("#next-stage").click();
 await desktop.waitForFunction(()=>window.__luminaQA?.get().stageIndex===1);
 if(await desktop.evaluate(()=>window.__luminaQA.get().bpm)!==128)throw Error("Stage 2 should play at 128 BPM");
 await desktop.evaluate(()=>window.__luminaQA.win());
 await desktop.locator("#next-stage").click();
 await desktop.waitForFunction(()=>window.__luminaQA?.get().stageIndex===2);
 if(await desktop.evaluate(()=>window.__luminaQA.get().bpm)!==160)throw Error("Stage 3 should play at 160 BPM");
 await desktop.evaluate(()=>window.__luminaQA.win());
 if(!(await desktop.locator("#next-stage").isHidden()))throw Error("Final stage must not have next button");
 const saved=await desktop.evaluate(()=>JSON.parse(localStorage.getItem("lumina-progress-v2")));
 if(saved.unlocked!==3||!saved.levels.every(x=>x&&typeof x.score==="number"))throw Error("Three-level local save failed");
 await desktop.screenshot({path:path.join(__dirname,"screenshot-result.png"),fullPage:true});
 await desktop.locator("#home").click();
 await desktop.setViewportSize({width:390,height:844});
 const mobile=desktop;
 await mobile.locator("#start").click();
 await mobile.waitForFunction(()=>window.__luminaQA?.get().mode==="playing");
 const coords=await mobile.evaluate(()=>{
  const rect=id=>{let b=document.getElementById(id).getBoundingClientRect();return {x:b.x,y:b.y,w:b.width,h:b.height}};
  return {left:rect("left"),right:rect("right"),pulse:rect("pulse"),hud:rect("progress-fill"),viewport:{w:innerWidth,h:innerHeight}}
 });
 if(Math.abs(coords.left.y-coords.right.y)>3)throw Error("Left / right buttons not aligned: "+JSON.stringify(coords));
 if(coords.pulse.y+coords.pulse.h>coords.right.y-5)throw Error("Pulse should be above right button: "+JSON.stringify(coords));
 if(coords.right.x<=coords.left.x)throw Error("Right key isn't at bottom right");
 if(coords.viewport.h-(coords.right.y+coords.right.h)<55)throw Error("Controls still too near bottom to reach: "+JSON.stringify(coords));
 if(coords.right.w<72||coords.right.h<72)throw Error("Touch target too small: "+JSON.stringify(coords));
 if(coords.pulse.y+coords.pulse.h>coords.right.y-14)throw Error("Pulse not clearly separated above right control");
 if(coords.hud.y+coords.hud.h>coords.pulse.y-10)throw Error("HUD overlaps pulse controls: "+JSON.stringify(coords));
 if(!(await mobile.locator("#beat-hit").isVisible()))throw Error("Missing touch HIT button");
 const hitRect=await mobile.locator("#beat-hit").boundingBox();
 if(!hitRect||hitRect.width<70||hitRect.x<65||hitRect.x+hitRect.width>coords.viewport.w-65)throw Error("Touch HIT placement incorrect");
 await mobile.locator("#beat-hit").tap();
 await mobile.locator("#right").click();
 const afterRight=await mobile.evaluate(()=>window.__luminaQA.get().targetLane);
 if(afterRight!==2)throw Error("Mobile right steering not triggered");
 const prePulse=await mobile.evaluate(()=>{const n=window.__luminaQA.pulseTest();return {...window.__luminaQA.get(),spawned:n}});
 if(prePulse.spawned<2)throw Error("Failed to spawn pulse test drones");
 await mobile.locator("#pulse").click();
 const postPulse=await mobile.evaluate(()=>window.__luminaQA.get());
 if(postPulse.pulseIn<=0)throw Error("Mobile pulse not triggered");
 if(postPulse.enemyCount>prePulse.enemyCount-2)throw Error("Pulse failed to clear both distant drones across lanes");
 if(postPulse.shield<75)throw Error("Pulse failed to restore 20 percent shield");
 if(!(await mobile.locator("#pulse").isDisabled()))throw Error("Pulse cooldown button did not disable");
 if(!(await mobile.locator("#pulse-fx").evaluate(n=>n.classList.contains("on"))))throw Error("Pulse screen burst did not fire");
 await mobile.waitForTimeout(1150);
 const projection=await mobile.evaluate(()=>window.__luminaQA.get().playerScreen);
 if(Math.abs(projection.x)>.85||Math.abs(projection.y)>.77)throw Error("Player exits portrait camera: "+JSON.stringify(projection));
 await mobile.waitForTimeout(800);
 await mobile.screenshot({path:path.join(__dirname,"screenshot-mobile.png"),fullPage:true});
 if(errors.length)throw Error(errors.join("\n"));
 console.log("PASS: WebGL desktop and mobile load, 3 stage transition/unlock, local save, control layout");
 await browser.close()
})().catch(e=>{console.error(e);process.exit(1)});
